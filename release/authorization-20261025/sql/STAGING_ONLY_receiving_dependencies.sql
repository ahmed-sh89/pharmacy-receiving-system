CREATE OR REPLACE FUNCTION public.pharmflow_is_member(p_pharmacy_id uuid)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
 select exists(select 1 from public.system_owners so where so.user_id=auth.uid())
 or exists(select 1 from public.pharmacy_members pm where pm.pharmacy_id=p_pharmacy_id and pm.user_id=auth.uid());
$function$
;
REVOKE ALL ON FUNCTION public.pharmflow_is_member(uuid) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.pharmflow_is_member(uuid) TO authenticated;
GRANT EXECUTE ON FUNCTION public.pharmflow_is_member(uuid) TO anon;
GRANT EXECUTE ON FUNCTION public.pharmflow_is_member(uuid) TO service_role;
CREATE OR REPLACE FUNCTION public.pharmflow_gtin_lifecycle_member_v3(p_pharmacy_id uuid)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
    select auth.uid() is not null
       and (
            exists (
                select 1
                  from public.system_owners so
                 where so.user_id = auth.uid()
            )
            or (
                public.pharmflow_is_member(p_pharmacy_id)
                and exists (
                    select 1
                      from public.pharmacy_members pm
                     where pm.pharmacy_id = p_pharmacy_id
                       and pm.user_id = auth.uid()
                       and pm.active is true
                )
            )
       );
$function$
;
REVOKE ALL ON FUNCTION public.pharmflow_gtin_lifecycle_member_v3(uuid) FROM PUBLIC,anon,authenticated;

